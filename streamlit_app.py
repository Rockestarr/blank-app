def safe_divide(numerator, denominator):

    if (
        numerator is None
        or denominator is None
        or denominator == 0
    ):
        return None

    return numerator / denominator


def growth(current, previous):

    if (
        current is None
        or previous is None
        or previous == 0
    ):
        return None

    return current / previous - 1


def first_value(dictionary, possible_keys):

    for key in possible_keys:

        value = dictionary.get(key)

        if value is not None:
            return value

    return None


def calculate_fcf(row):

    direct_fcf = row.get("freeCashFlow")

    if direct_fcf is not None:
        return direct_fcf

    operating_cash_flow = row.get(
        "operatingCashFlow"
    )

    capital_expenditure = row.get(
        "capitalExpenditure"
    )

    if (
        operating_cash_flow is not None
        and capital_expenditure is not None
    ):
        return (
            operating_cash_flow
            - abs(capital_expenditure)
        )

    return None


