def money_short(value):

    if value is None:
        return "N/A"

    value = float(value)

    sign = "-" if value < 0 else ""

    absolute_value = abs(value)

    if absolute_value >= 1_000_000_000_000:

        return (
            f"{sign}$"
            f"{absolute_value / 1_000_000_000_000:,.2f}T"
        )

    if absolute_value >= 1_000_000_000:

        return (
            f"{sign}$"
            f"{absolute_value / 1_000_000_000:,.2f}B"
        )

    if absolute_value >= 1_000_000:

        return (
            f"{sign}$"
            f"{absolute_value / 1_000_000:,.2f}M"
        )

    return f"{sign}${absolute_value:,.0f}"


def money_full(value):

    if value is None:
        return "N/A"

    value = float(value)

    if value < 0:
        return f"-${abs(value):,.0f}"

    return f"${value:,.0f}"


def number_full(value):

    if value is None:
        return "N/A"

    return f"{float(value):,.0f}"


def percent(value, digits=1):

    if value is None:
        return "N/A"

    return f"{value * 100:,.{digits}f}%"


def multiple(value):

    if value is None:
        return "N/A"

    return f"{value:,.2f}x"


def shares_format(value):

    if value is None:
        return "N/A"

    value = float(value)

    if value >= 1_000_000_000:

        return (
            f"{value / 1_000_000_000:,.2f}B"
        )

    if value >= 1_000_000:

        return (
            f"{value / 1_000_000:,.1f}M"
        )

    return f"{value:,.0f}"


def metric(
    column,
    label,
    value,
    definition_key=None,
    delta=None
):
    help_text = DEFINITIONS.get(
        definition_key or label
    )

    column.metric(
        label=label,
        value=value,
        delta=delta,
        help=help_text
    )


