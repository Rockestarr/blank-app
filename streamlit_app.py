def score_growth(
    revenue_growth,
    eps_growth
):
    score = 0

    if revenue_growth is not None:

        if revenue_growth >= 0.20:
            score += 10

        elif revenue_growth >= 0.10:
            score += 8

        elif revenue_growth >= 0.05:
            score += 5

        elif revenue_growth > 0:
            score += 2

    if eps_growth is not None:

        if eps_growth >= 0.25:
            score += 10

        elif eps_growth >= 0.15:
            score += 8

        elif eps_growth > 0:
            score += 5

    return min(score, 20)


