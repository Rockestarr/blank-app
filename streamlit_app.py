@st.cache_data(ttl=3600)
def get_fmp(
    endpoint,
    ticker,
    limit=5,
    period=None,
    required=True
):
    safe_limit = min(
        max(int(limit), 1),
        MAX_FMP_LIMIT
    )

    params = {
        "symbol": ticker,
        "limit": safe_limit,
        "apikey": FMP_API_KEY
    }

    if period:
        params["period"] = period

    response = requests.get(
        f"{BASE_URL}/{endpoint}",
        params=params,
        timeout=30
    )

    if response.status_code != 200:

        if required:
            raise Exception(
                f"FMP API error {response.status_code} "
                f"from {endpoint}: {response.text}"
            )

        return []

    data = response.json()

    if not isinstance(data, list) or not data:

        if required:
            raise Exception(
                f"No data returned from {endpoint}. "
                "Check the ticker or your FMP access."
            )

        return []

    return data


