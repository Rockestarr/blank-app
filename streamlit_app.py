def analyst_report(metrics):

    strengths = []
    watch_items = []
    concerns = []

    revenue_growth = metrics[
        "revenue_growth"
    ]

    if revenue_growth is not None:

        if revenue_growth >= 0.10:

            strengths.append(
                f"TTM revenue increased "
                f"{percent(revenue_growth)}."
            )

        elif revenue_growth >= 0:

            watch_items.append(
                f"TTM revenue growth is only "
                f"{percent(revenue_growth)}."
            )

        else:

            concerns.append(
                f"TTM revenue declined "
                f"{percent(abs(revenue_growth))}."
            )

    operating_margin = metrics[
        "operating_margin"
    ]

    previous_operating_margin = metrics[
        "previous_operating_margin"
    ]

    if (
        operating_margin is not None
        and previous_operating_margin is not None
    ):

        margin_change = (
            operating_margin
            - previous_operating_margin
        )

        if margin_change >= 0.02:

            strengths.append(
                f"Operating margin expanded by "
                f"{margin_change * 100:,.1f} "
                f"percentage points."
            )

        elif margin_change <= -0.02:

            concerns.append(
                f"Operating margin contracted by "
                f"{abs(margin_change) * 100:,.1f} "
                f"percentage points."
            )

        else:

            watch_items.append(
                "Operating margin is relatively stable."
            )

    free_cash_flow = metrics[
        "free_cash_flow"
    ]

    if free_cash_flow is not None:

        if free_cash_flow > 0:

            strengths.append(
                f"The company generated "
                f"{money_short(free_cash_flow)} "
                f"of TTM free cash flow."
            )

        else:

            concerns.append(
                "TTM free cash flow is negative."
            )

    net_cash = metrics["net_cash"]

    if net_cash is not None:

        if net_cash > 0:

            strengths.append(
                f"The company has "
                f"{money_short(net_cash)} "
                f"of net cash."
            )

        else:

            watch_items.append(
                f"Debt exceeds cash by "
                f"{money_short(abs(net_cash))}."
            )

    share_change = metrics[
        "share_change"
    ]

    if share_change is not None:

        if share_change <= 0:

            strengths.append(
                "The diluted share count is "
                "flat or declining."
            )

        elif share_change <= 0.02:

            watch_items.append(
                f"Diluted shares increased "
                f"{percent(share_change)}, "
                f"representing mild dilution."
            )

        else:

            concerns.append(
                f"Diluted shares increased "
                f"{percent(share_change)}, "
                f"creating meaningful dilution."
            )

    pe_ratio = metrics["pe_ratio"]

    if pe_ratio is not None and pe_ratio >= 35:

        concerns.append(
            f"The {pe_ratio:,.1f}x P/E "
            f"represents a premium valuation."
        )

    fcf_yield = metrics["fcf_yield"]

    if fcf_yield is not None and fcf_yield < 0.03:

        concerns.append(
            f"Free-cash-flow yield is only "
            f"{percent(fcf_yield)}, offering "
            f"limited valuation cushion."
        )

    return strengths, watch_items, concerns


