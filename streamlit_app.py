def build_ttm_income(quarterly_income):

    latest_four = quarterly_income[:4]

    if len(latest_four) < 4:
        return None

    ttm = {
        "date": latest_four[0].get("date"),
        "period": "TTM"
    }

    fields = [
        "revenue",
        "grossProfit",
        "operatingIncome",
        "netIncome"
    ]

    for field in fields:

        values = [
            row.get(field)
            for row in latest_four
        ]

        if any(
            value is not None
            for value in values
        ):

            ttm[field] = sum(
                value
                for value in values
                if value is not None
            )

        else:

            ttm[field] = None

    eps_values = [
        first_value(
            row,
            ["epsDiluted", "eps"]
        )
        for row in latest_four
    ]

    ttm["epsDiluted"] = sum(
        value
        for value in eps_values
        if value is not None
    )

    return ttm


def build_ttm_cashflow(
    quarterly_cashflow
):

    latest_four = quarterly_cashflow[:4]

    if len(latest_four) < 4:
        return None

    ttm = {
        "date": latest_four[0].get("date"),
        "period": "TTM"
    }

    fields = [
        "operatingCashFlow",
        "capitalExpenditure",
        "stockBasedCompensation"
    ]

    for field in fields:

        values = [
            row.get(field)
            for row in latest_four
        ]

        if any(
            value is not None
            for value in values
        ):

            ttm[field] = sum(
                value
                for value in values
                if value is not None
            )

        else:

            ttm[field] = None

    fcf_values = [
        calculate_fcf(row)
        for row in latest_four
    ]

    ttm["freeCashFlow"] = sum(
        value
        for value in fcf_values
        if value is not None
    )

    return ttm


